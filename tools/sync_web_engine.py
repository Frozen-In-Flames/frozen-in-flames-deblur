"""Sync the deblur package into docs/ for the GitHub Pages demo.

GitHub Pages serves the demo from docs/, so the Python engine the page
loads in the browser has to live under docs/ too. The files there are
byte-for-byte copies of deblur/*.py, generated by this script; never
edit them by hand.

    python tools/sync_web_engine.py           copy deblur/*.py to docs/deblur/
    python tools/sync_web_engine.py --check   fail if docs/deblur/ has drifted
"""

import filecmp
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "deblur"
DST = ROOT / "docs" / "deblur"


def package_files():
    return sorted(p for p in SRC.glob("*.py"))


def main(argv=None):
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    DST.mkdir(parents=True, exist_ok=True)
    drift = []
    for src in package_files():
        dst = DST / src.name
        if check:
            if not dst.exists() or not filecmp.cmp(src, dst, shallow=False):
                drift.append(src.name)
        else:
            shutil.copyfile(src, dst)
            print(f"synced {src.name}")
    # A file removed from the package must not linger in docs/.
    for dst in sorted(DST.glob("*.py")):
        if not (SRC / dst.name).exists():
            if check:
                drift.append(f"{dst.name} (stale)")
            else:
                dst.unlink()
                print(f"removed stale {dst.name}")
    if check:
        if drift:
            print("docs/deblur/ is out of sync: " + ", ".join(drift), file=sys.stderr)
            print("run: python tools/sync_web_engine.py", file=sys.stderr)
            return 1
        print("docs/deblur/ in sync with deblur/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
